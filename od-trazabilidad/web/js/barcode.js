const C128_STOP = '1100011101011';

function code128Modulos(txt){
  const s = String(txt ?? '');
  let start, vals;
  if (/^\d{4,}$/.test(s) && s.length % 2 === 0){
    start = 105; vals = [];
    for (let i = 0; i < s.length; i += 2) vals.push(+s.slice(i, i + 2));
  } else {
    start = 104;
    vals = [...s].map(c => { const n = c.charCodeAt(0) - 32; return n >= 0 && n <= 94 ? n : 31; });
  }
  let suma = start;
  vals.forEach((v, i) => { suma += v * (i + 1); });
  return [start, ...vals, suma % 103].map(v => C128[v]).join('') + C128_STOP;
}

/* SVG en una sola ruta; hereda el color del texto. */
function codigoBarrasSVG(txt, {modulo = 1.6, alto = 44, silencio = 10, etiqueta = ''} = {}){
  const m = code128Modulos(txt);
  let d = '', x = silencio;
  for (let i = 0; i < m.length;){
    let j = i; while (j < m.length && m[j] === m[i]) j++;
    if (m[i] === '1') d += `M${(x * modulo).toFixed(2)} 0h${((j - i) * modulo).toFixed(2)}v${alto}h-${((j - i) * modulo).toFixed(2)}z`;
    x += j - i; i = j;
  }
  const w = ((m.length + silencio * 2) * modulo).toFixed(2);
  return `<svg class="barras" viewBox="0 0 ${w} ${alto}" width="${w}" height="${alto}" role="img" aria-label="${esc(etiqueta || 'Código de barras ' + txt)}" shape-rendering="crispEdges"><path d="${d}" fill="currentColor"/></svg>`;
}
