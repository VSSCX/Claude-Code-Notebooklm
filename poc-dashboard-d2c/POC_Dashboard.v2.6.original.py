def puerto_libre(inicio=8000):
    for p in range(inicio, inicio + 11):
        with socket.socket() as s:
            if s.connect_ex(("127.0.0.1", p)) != 0:
                return p
    raise ErrorInstalador("No hay un puerto libre entre 8000 y 8010. Cierra otros programas.")


def iniciar(destino, py):
    puerto = puerto_libre()
    url = f"http://127.0.0.1:{puerto}"
    hablar(f"\n  Iniciando en {url}")
    hablar("  NO cierres esta ventana mientras uses el dashboard (cerrarla lo apaga).")
    hablar("  Para volver a abrirlo otro dia: doble clic en run.bat dentro de la carpeta.\n")
    proc = subprocess.Popen([str(py), "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1",
                             "--port", str(puerto)], cwd=str(destino))
    for _ in range(60):
        if proc.poll() is not None:
            raise ErrorInstalador("El servidor se detuvo al iniciar. Ejecuta run.bat para ver el detalle.")
        try:
            urllib.request.urlopen(url + "/api/config", timeout=2)
            break
        except Exception:
            time.sleep(0.5)
    try:
        webbrowser.open(url)
    except Exception:
        pass
    try:
        proc.wait()
    except KeyboardInterrupt:
        proc.terminate()
        hablar("\n  Dashboard detenido.")


